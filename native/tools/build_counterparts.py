"""Compile verified character pairs and portable motion indexes for the game runtime."""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_ch9_skill_map import archived, motion, name, normalized
from build_named_clash_slots import read_archive


def clips(groups):
    result = {}
    for detail, parts in groups.items():
        if detail not in (*range(7, 17), *range(24, 35)):
            continue
        parts = sorted(parts)
        if all(i == at and n == len(parts) and duration > 0
               for at, (i, n, duration, _) in enumerate(parts)):
            result[detail] = tuple(round(p[2], 5) for p in parts)
    return result


def index_skills(static, data):
    skills, owners = {}, defaultdict(set)
    for path, doc in static.items():
        for row in doc.get('list', []) if isinstance(doc, dict) else ():
            if not isinstance(row, dict):
                continue
            if 'skillData' in row and isinstance(row['skillData'], list):
                skills[row['id']] = row
            elif ('/enemy/' in path or '/abnormality-unit/' in path) and row.get('appearance'):
                ids = owners[row['appearance']]
                ids.update(s['skillId'] for s in row.get('attributeList', []) if s.get('skillId'))
                ids.update(row.get('defenseSkillIDList', []))
    enemy = archived(data, 'enemy_db')['skills']
    players = archived(data, 'unit_db')['ids']

    def actions(rows):
        result = defaultdict(set)
        for skill_id, label in rows:
            slot = motion(skills.get(skill_id, {}))
            if slot:
                result[slot[0]].add((slot[1], normalized(label)))
        return result

    return ({p['id']: actions((s['id'], name(s)) for s in p['skills'] + p['defense']) for p in players},
            {look: actions((i, name(enemy.get(str(i), {}))) for i in ids) for look, ids in owners.items()})


def align(source, donor, source_skills, donor_skills):
    rows = []
    for src, durations in source.items():
        labels = source_skills.get(src, set())
        common = [dst for dst in donor if labels and all(label for _, label in labels)
                  and labels <= donor_skills.get(dst, set())]
        # A multi-part sequence with identical native durations identifies the
        # same performance in a verified pair only when the match is unique.
        timed = [dst for dst in donor if len(durations) > 1 and durations == donor[dst]
                 and len(set(durations)) > 1 and list(source.values()).count(durations) == 1]
        options = common if common else timed
        if len(options) == 1:
            dst = options[0]
            rows.append((src, dst, len(donor[dst])))
    return rows


def main():
    p = argparse.ArgumentParser()
    for arg in ('pairs', 'timings', 'static', 'database', 'output'):
        p.add_argument(arg, type=Path)
    args = p.parse_args()
    registry = json.loads(args.pairs.read_bytes())
    rows = registry['pairs']
    archive = read_archive(args.timings)
    players, enemies = index_skills(json.loads(args.static.read_bytes()), args.database)
    pairs, maps = [], []
    parts = {}
    slots = (*range(7, 17), *range(24, 35))
    for row in sorted(rows, key=lambda r: (r['identity'], r['appearance'])):
        player, story = row['personality'], row['appearance'].removeprefix('story_')
        assert player.startswith(str(row['identity'])+'_') and story != row['appearance']
        a, b = players.get(row['identity'], {}), enemies.get(story, {})
        for variant in dict.fromkeys([player, *row.get('aliases', [])]):
            assert variant.startswith(str(row['identity']) + '_')
            source, target = clips(archive.get(variant, {})), clips(archive.get(story, {}))
            forward = align(source, target, a, b)
            reverse = align(target, source, b, a)
            pool = row.get('pool_id', row['appearance'])
            sizes = [tuple(len(groups.get(slot, ())) for slot in slots) for groups in (source, target)]
            src, dst = (parts.setdefault(s, len(parts)) for s in sizes)
            pairs.append((row['identity'], variant, story, pool, len(maps), len(forward), len(reverse), src, dst))
            maps.extend(forward + reverse)
    assert len({(p[1], p[2]) for p in pairs}) == len(pairs) and pairs
    output = ['/* Generated by build_counterparts.py. */','static const SrCounterpart sr_counterparts[]={']
    for pid, player, story, pool, first, forward, reverse, src, dst in pairs:
        output.append(' {%d,%s,%s,%s,%d,%d,%d,%d,%d},' % (pid,json.dumps(player),json.dumps(story),json.dumps(pool),first,forward,reverse,src,dst))
    output += ['};','static const unsigned char sr_counterpart_lengths[][21]={']
    for lengths in parts:
        assert max(lengths) < 256
        output.append(' {'+','.join(map(str,lengths))+'},')
    output += ['};','static const SrCounterpartMotion sr_counterpart_motions[]={']
    output.extend(' {%d,%d,%d},' % row for row in maps)
    output += ['};','static const SrCounterpartForm sr_counterpart_forms[]={']
    for form in registry.get('native_forms', []):
        normal, alternate = form['player']
        base, changed = form['appearances']
        assert all(any(r['identity']==form['identity'] and r['pool_id']==look and
                       normal==r['personality'] and alternate in r['aliases'] for r in rows)
                   for look in (base, changed))
        output.append(' {%s,%s,%s,%s,%s},' % tuple(json.dumps(s) for s in
                      (normal, alternate, base, changed, 'pair'+str(form['identity']))))
    output += [' {0}', '};','']
    args.output.write_text('\n'.join(output), encoding='ascii')
    print(len(rows), 'appearance pairs;', len(pairs), 'including player variants;',
          sum(p[5] for p in pairs), 'forward and', sum(p[6] for p in pairs), 'reverse motion groups')


if __name__ == '__main__':
    main()
