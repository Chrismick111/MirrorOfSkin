"""Index explicitly named duel groups outside the usual slots, using shipped ATX records."""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import struct
import zipfile

HEADER = struct.Struct('<I96sI')
CLIP = struct.Struct('<iiid128s')
STANDARD = {1:36, 2:37, 3:38, 4:17}
PATTERNS = (
    (1, re.compile(r'(?:^|_)(?:duel|clash|parrying)_?ready(?:_timeline)?(?:_\d+)?$',re.I)),
    (2, re.compile(r'(?:^|_)(?:duel|clash|parrying)_?win(?:_timeline)?(?:_\d+)?$',re.I)),
    (3, re.compile(r'(?:^|_)(?:duel|clash|parrying)_?lose(?:_timeline)?(?:_\d+)?$',re.I)),
    (4, re.compile(r'(?:^|_)parrying_timeline(?:_\d+)?$',re.I)),
)


def timeline_role(name):
    if re.search(r'(?:^|_)(?:summon|special|actor|target|link)(?:_|$)', name, re.I):
        return None
    return next((role for role, pattern in PATTERNS if pattern.search(name)), None)


def read_archive(folder):
    result = {}
    for path in sorted(folder.glob('*.bin')):
        data = path.read_bytes()
        magic, appearance, n = HEADER.unpack_from(data)
        if magic != 0x31585441 or len(data) != HEADER.size + n * CLIP.size:
            raise ValueError(path)
        groups = defaultdict(list)
        for detail,index,count,duration,name in CLIP.iter_unpack(data[HEADER.size:]):
            groups[detail].append((index,count,duration,name.rstrip(b'\0').decode('ascii')))
        result[appearance.rstrip(b'\0').decode('ascii')] = groups
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('addon', type=Path)
    parser.add_argument('header', type=Path)
    parser.add_argument('report', type=Path)
    parser.add_argument('--legacy-flags', type=Path)
    parser.add_argument('--baseline', type=Path, help='Original 0.78 distribution for its default exclusions')
    args = parser.parse_args()
    archive = read_archive(args.addon/'archive-times-candidate')
    catalog = json.loads((args.addon/'Assets/runtime/all_sinners_pools.json').read_bytes())
    entries = {e['identity_id']:e for pool in catalog.values() for e in pool['entries']}
    if args.legacy_flags and not args.baseline:
        parser.error('--legacy-flags requires the release whose defaults are being upgraded')
    legacy_entries = {}
    if args.baseline:
        with zipfile.ZipFile(args.baseline) as bundle:
            old = json.loads(bundle.read('Assets/runtime/all_sinners_pools.json'))
        legacy_entries = {e['identity_id']:e for pool in old.values() for e in pool['entries']}
    records = []
    audit = {}
    legacy = []
    for identity,e in sorted(entries.items()):
        look = e['appearance_name']
        groups = archive.get(look, {})
        roles = []
        for detail,clips in sorted(groups.items()):
            indexed = sorted(clips)
            if not all(k==i and n==len(indexed) and t>0 for i,(k,n,t,_) in enumerate(indexed)):
                continue
            names = [clip[-1] for clip in indexed]
            identified = {timeline_role(name) for name in names}
            role = identified.pop() if len(identified)==1 else None
            if not role:
                continue
            roles.append(dict(role=role,detail=detail,timelines=names))
            if (detail!=STANDARD[role] or role in (2,3)) and detail not in (41,42,43):
                records.append((look,role,detail))
        audit[identity] = dict(appearance=look, indexed=look in archive,
                               standard_timeline_details=sorted(set(groups)&{17,19,23,36,37,38,41,42,43}),
                               named=roles)
        prior = legacy_entries.get(identity, {})
        if (prior.get('appearance_name')==look and prior.get('excluded_actions') == ['evade','clash'] and not e.get('no_attack') and
            (groups.get(17) or any(r['role'] in (2,3,4) for r in roles))):
            legacy.append(identity)
    header=['/* Generated by build_named_clash_slots.py from complete, named timeline groups. */',
            '#ifndef SR_NAMED_CLASH_SLOTS_H', '#define SR_NAMED_CLASH_SLOTS_H', '#include <string.h>',
            'static const struct {const char *look;int role,detail;} sr_named_clashes[]={']
    rows=sorted(set(records))
    header.extend(' {%s,%d,%d},'%(json.dumps(look),role,detail) for look,role,detail in rows)
    header += ['};','static int sr_named_clash_slot(const char *look,int role,int ordinal){',
               ' if(!look||ordinal<0)return -1;',
               ' for(unsigned i=0;i<sizeof(sr_named_clashes)/sizeof(sr_named_clashes[0]);i++){',
               '  if(sr_named_clashes[i].role==role&&!strcmp(sr_named_clashes[i].look,look)&&ordinal--==0)return sr_named_clashes[i].detail;',
               ' }return -1;','}', '#endif','']
    args.header.write_text('\n'.join(header),encoding='ascii')
    args.report.parent.mkdir(parents=True,exist_ok=True)
    args.report.write_text(json.dumps(dict(role_names={1:'拼点准备',2:'拼点胜利',3:'拼点失败',4:'普通拼点'},
                                           appearances=audit),ensure_ascii=False,indent=1),encoding='utf8')
    if args.legacy_flags:
        args.legacy_flags.write_text(json.dumps(legacy,indent=1)+'\n',encoding='ascii')
    print(len(entries),'catalog entries;',sum(row['indexed'] for row in audit.values()),'indexed;',
          len(rows),'named fallback groups across',len(set(r[0] for r in rows)),'looks')


if __name__=='__main__':
    main()
